export const getArtworkBySlug = (slug: string): Artwork | undefined =>
  artworks.find((a) => a.slug === slug);

export const getArtworkById = (id: string): Artwork | undefined =>
  artworks.find((a) => a.id === id);

export const getArtworksByArtist = (artistId: string): Artwork[] =>
  artworks.filter((a) => a.artistId === artistId);

export const getFeaturedArtworks = (): Artwork[] =>
  artworks.filter((a) => a.featured);

export const getNewArrivals = (): Artwork[] =>
  artworks.filter((a) => a.newArrival);

export const getArtworkCategories = (): string[] =>
  [...new Set(artworks.map((a) => a.category))].sort();

export const getArtworkMediums = (): string[] =>
  [...new Set(artworks.map((a) => a.medium))].sort();

export const getRelatedArtworks = (artworkId: string, limit = 4): Artwork[] =>
  artworks.filter((a) => a.id !== artworkId).slice(0, limit);
